/**
 * Curated public-domain authors for the Wikisource aggregator.
 *
 * LEGAL NOTE — only authors safely in the public domain belong here.
 * Russian/Kazakh copyright runs life + 70 years, so everyone listed died before
 * ~1955. Do NOT add living or recently-deceased authors: Wikisource hosts only
 * free content, but adding a still-copyrighted name would surface texts we have
 * no right to distribute. When in doubt, leave it out.
 *
 * Each author fully specifies its source so the aggregator needs no global lang:
 *  - `page`   exact Wikisource page title (ru authors use the "Автор:" namespace;
 *             Kazakh authors are plain pages on the multilingual wiki).
 *  - `host`   MediaWiki API host to read the author's linked works from.
 *  - `wsLang` WSexport `lang` param used to render each work into an EPUB.
 *  - `lang`   catalog language code stored on the book ('ru' | 'kk').
 *
 * Kazakh has no dedicated kk.wikisource subdomain; its texts live on the
 * multilingual wiki (www.wikisource.org, WSexport lang "www").
 */
export interface WikiAuthor {
  page: string;
  name: string;
  host: string;
  wsLang: string;
  lang: string;
}

// Russian author on ru.wikisource (works under the "Автор:" namespace).
const ru = (page: string, name: string): WikiAuthor => ({
  page: `Автор:${page}`,
  name,
  host: 'ru.wikisource.org',
  wsLang: 'ru',
  lang: 'ru',
});

// Kazakh author on the multilingual wiki (plain page title, WSexport lang "www").
const kk = (page: string, name: string): WikiAuthor => ({
  page,
  name,
  host: 'www.wikisource.org',
  wsLang: 'www',
  lang: 'kk',
});

